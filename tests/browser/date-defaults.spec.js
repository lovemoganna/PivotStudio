import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
import {clickExport} from './_toolbar.js';
import {ensureMobileShelves} from './_mobileShelves.js';
const ready=p=>expect(p.getByTestId('pivot-workbench')).toHaveAttribute('data-calculation-status','idle');
const times=['2027-02-03 10:20:30.125','2027-02-03 10:20:30.875','2027-02-03 10:20:31.000'];
const csv='Team,RecordedAt,Reading\n'+times.map((time,i)=>`A,${time},${[10,20,40][i]}`).join('\n');
for(const width of [360,768,1440])test(`dates: preserve source precision, explicit second/minute grouping and history at ${width}`,async({page},info)=>{
  await page.setViewportSize({width,height:1050});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.route('https://fonts.googleapis.com/**',r=>r.abort());
  await page.route('https://fonts.gstatic.com/**',r=>r.abort());
  await page.goto('/');
  await page.locator('input[type=file]').first().setInputFiles({name:'synthetic-timestamps.csv',mimeType:'text/csv',buffer:Buffer.from(csv)});
  await page.getByRole('button',{name:'确认导入并自动构建推荐透视',exact:true}).click();await ready(page);
  await page.screenshot({path:info.outputPath('initial-date-view.png')});
  for(const time of times)await expect(page.locator('#pivot-main-html-table thead')).toContainText(time);
  await page.getByRole('button',{name:/调整图表字段:/}).click();
  await page.getByLabel('行字段',{exact:true}).selectOption('RecordedAt');await ready(page);
  for(const time of times)await expect(page.locator('#pivot-main-html-table')).toContainText(time);
  await ensureMobileShelves(page,width);
  if(width>=768)await page.getByRole('button',{name:'配置',exact:true}).click();
  // Table grouping is an explicit sidebar operation; chart field edits no longer rewrite it.
  if(width>=768)await page.getByRole('button',{name:'分栏',exact:true}).click();
  await page.getByTestId('zone-rows').getByRole('button',{name:'移除字段',exact:true}).click();await ready(page);
  await page.getByTestId('zone-columns').getByRole('button',{name:'移除字段',exact:true}).click();await ready(page);
  await page.getByRole('button',{name:'+行 · 添加「RecordedAt」到行分组',exact:true}).press('Enter');await ready(page);
  const dateCard=page.getByTestId('zone-rows');
  await dateCard.getByTitle('分组设置',{exact:true}).click();
  const modal=page.getByRole('dialog',{name:'字段分组设置',exact:true});
  await expect(modal.getByRole('button',{name:'原始日期与时间 (Raw)',exact:true})).toHaveAttribute('aria-pressed','true');
  await modal.screenshot({path:info.outputPath('date-granularities.png')});
  await modal.getByRole('button',{name:'按秒 (Second)',exact:true}).click();await ready(page);
  const cells=page.getByTestId('pivot-value-cell');
  await expect(cells).toHaveText(['30','40']);
  await expect(page.locator('#pivot-main-html-table')).toContainText('2027-02-03 10:20:30');
  await dateCard.getByTitle('分组设置',{exact:true}).click();
  await modal.getByRole('button',{name:'按分钟 (Minute)',exact:true}).click();await ready(page);
  await expect(cells).toHaveText(['70']);
  await page.getByRole('button',{name:'撤销',exact:true}).press('Enter');await ready(page);
  await expect(cells).toHaveText(['30','40']);
  await page.getByRole('button',{name:'撤销',exact:true}).press('Enter');await ready(page);
  await expect(cells).toHaveText(['10','20','40']);
  const dl=page.waitForEvent('download');await clickExport(page,'.CSV');
  const exported=await readFile(await(await dl).path(),'utf8');
  for(const time of times)expect(exported).toContain(time);
  await page.getByLabel('列字段',{exact:true}).selectOption('RecordedAt');await ready(page);
  await expect(page.getByLabel('列字段',{exact:true})).toHaveValue('RecordedAt');
  for(const time of times)await expect(page.locator('#pivot-main-html-table')).toContainText(time);
  // Sidebar manual additions use the same raw default after removing the column.
  await page.getByLabel('列字段',{exact:true}).selectOption('');await ready(page);
  if(width>=768)await page.getByRole('button',{name:'分栏',exact:true}).click();
  await dateCard.getByRole('button',{name:'移除字段',exact:true}).click();await ready(page);
  await page.getByRole('button',{name:'+行 · 添加「RecordedAt」到行分组',exact:true}).press('Enter');await ready(page);
  for(const time of times)await expect(page.locator('#pivot-main-html-table')).toContainText(time);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1);
  await page.screenshot({path:info.outputPath(`date-defaults-${width}.png`),fullPage:true});
});
