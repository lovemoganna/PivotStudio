import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import {encodeView} from '../../src/utils/viewConfig.js';
import {ensureMobileShelves} from './_mobileShelves.js';
import {readFile} from 'node:fs/promises';
const ready=p=>expect(p.getByTestId('pivot-workbench')).toHaveAttribute('data-calculation-status','idle');
for(const width of [360,768,1440]) test(`reading: current configuration, calculation guidance and authored notes at ${width}`,async({page},info)=>{
 await page.setViewportSize({width,height:1000});await page.emulateMedia({reducedMotion:'reduce'});
 await page.route('https://fonts.googleapis.com/**',r=>r.abort());await page.route('https://fonts.gstatic.com/**',r=>r.abort());
 const config={rows:[{id:'g',field:'Group'}],values:[{id:'v',field:'Value',agg:'stddev',format:{decimals:2}}]};
 await page.goto('/#share_token='+encodeURIComponent(encodeView({fullConfig:config,vm:'chart'})));
 await page.locator('input[type=file]').first().setInputFiles({name:'measurements.csv',mimeType:'text/csv',buffer:Buffer.from('Group,Value,Capacity\nAlpha,10,100\nAlpha,30,100\nBeta,60,200\nBeta,,200')});
 await page.getByRole('button',{name:'确认导入并自动构建推荐透视',exact:true}).click();await ready(page);
 await page.getByRole('button',{name:'阅读提示',exact:true}).click();
 const guide=page.getByTestId('chart-guide-note'),note=guide.getByTestId('chart-note-body');
 await expect(guide).toContainText('配置摘要');await expect(note).toContainText('Value（标准差）');
 await expect(note).not.toContainText('Capacity');await expect(note).not.toContainText('Alpha');
 const download=page.waitForEvent('download');await guide.getByRole('button',{name:'导出',exact:true}).click();
 const file=await download;expect(file.suggestedFilename()).toMatch(/\.md$/);
 const report=await readFile(await file.path(),'utf8');expect(report).toContain('Value（标准差）');
 expect(report.split('## 二、关键发现')[0]).not.toContain('Capacity');expect(report).not.toContain('出现较多');
 await guide.getByTestId('chart-metric-reading').locator('summary').press('Enter');
 await expect(guide).toContainText('样本口径（n−1）');await expect(guide.getByTestId('reference-mean-reading')).toBeVisible();
 await ensureMobileShelves(page,width);await page.getByRole('combobox',{name:'切换聚合口径',exact:true}).selectOption('avg');await ready(page);
 await expect(note).toContainText('Value（平均值）');await expect(guide.getByTestId('chart-metric-reading')).not.toContainText('样本口径');
 await guide.getByRole('button',{name:'编辑',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:/编辑分析笔记/});
 await expect(dialog.getByLabel('分析结论:',{exact:true})).not.toHaveValue(/Capacity|出现较多/);
 await dialog.getByLabel('分析结论:',{exact:true}).fill('我已核查此指标，仍需比较不同分组。');
 await dialog.getByRole('button',{name:'保存修改',exact:true}).click();await expect(dialog).toHaveCount(0);
 await expect(guide).toContainText('我的结论');await expect(note).toHaveText('我已核查此指标，仍需比较不同分组。');
 await page.getByRole('combobox',{name:'切换聚合口径',exact:true}).selectOption('median');await ready(page);
 await expect(note).toHaveText('我已核查此指标，仍需比较不同分组。');await expect(guide).toContainText('用户笔记不会随配置自动改写');
 await expect(guide.getByTestId('chart-metric-reading')).toContainText('中间两值');
 await page.screenshot({path:info.outputPath(`reading-${width}.png`),fullPage:true});
 expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
