import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
import AxeBuilder from '@axe-core/playwright';
import {encodeView} from '../../src/utils/viewConfig.js';

const config={rows:[{id:'r',field:'Region'}],columns:[{id:'c',field:'Period'}],values:[{id:'v',field:'Revenue',agg:'sum'}],filters:[]};
const csv='Region,Counterparty,Side,Period,Revenue,Volume\nA,X,Buy,P1,10,1\nA,Y,Sell,P1,20,2\nB,X,Sell,P2,30,3\nB,Y,Buy,P2,40,4\nA,X,Buy,P2,50,5\nB,Z,Sell,P1,60,6';
const ready=p=>expect(p.getByTestId('pivot-workbench')).toHaveAttribute('data-calculation-status','idle');
for(const width of [360,768,1440])test(`chart edits and filtering preserve table; separate drill and saved configuration at ${width}`,async({page},info)=>{
  await page.setViewportSize({width,height:1100});await page.emulateMedia({reducedMotion:'reduce'});
  await page.route('https://fonts.googleapis.com/**',route=>route.abort());await page.route('https://fonts.gstatic.com/**',route=>route.abort());
  await page.goto('/#share_token='+encodeURIComponent(encodeView({fullConfig:config,csc:{showDataLabels:true}})));
  await page.locator('input[type=file]').first().setInputFiles({name:'independent.csv',mimeType:'text/csv',buffer:Buffer.from(csv)});
  await page.getByRole('button',{name:'确认导入并自动构建推荐透视',exact:true}).click();await ready(page);
  const table=page.locator('#pivot-main-html-table'),before=await table.innerText();
  const summaryBefore=await page.getByTestId('overall-summary').innerText();
  const chart=page.locator('#pivot-chart-container');
  await expect(page.getByRole('button',{name:'撤销',exact:true})).toBeDisabled();
  await chart.getByRole('button',{name:/调整图表字段/}).click();
  await chart.getByLabel('行字段',{exact:true}).selectOption('Counterparty');await ready(page);
  await chart.getByLabel('列字段',{exact:true}).selectOption('Side');await ready(page);
  await chart.getByLabel('值字段',{exact:true}).selectOption('Volume');await ready(page);
  await expect(table).toHaveText(before,{useInnerText:true});
  await expect(page.getByTestId('overall-summary')).toHaveText(summaryBefore);
  await expect(chart.getByTestId('chart-analysis-state')).toHaveText('图表独立配置');
  await expect(page.getByRole('button',{name:'撤销',exact:true})).toBeDisabled();
  await chart.getByRole('button',{name:'互换行与列',exact:true}).click();await ready(page);
  await expect(chart.getByLabel('行字段',{exact:true})).toHaveValue('Side');
  await expect(table).toHaveText(before,{useInnerText:true});
  await chart.getByRole('button',{name:'互换行与列',exact:true}).click();await ready(page);
  await chart.getByRole('button',{name:'图表排序',exact:true}).click();await ready(page);
  await chart.getByLabel('选择图表类型',{exact:true}).selectOption('line');await ready(page);
  await chart.getByLabel('选择图表类型',{exact:true}).selectOption('bar');await ready(page);
  await expect(table).toHaveText(before,{useInnerText:true});
  // Remove series and reset ordering to make the first plotted group X, across all its records.
  await chart.getByLabel('列字段',{exact:true}).selectOption('');await ready(page);
  await chart.getByRole('button',{name:'图表排序',exact:true}).click();await ready(page);
  await chart.getByRole('button',{name:'图表排序',exact:true}).click();await ready(page);
  await chart.locator('.recharts-bar-rectangle').first().click();
  const details=page.getByRole('dialog',{name:'原始交易明细下钻',exact:true});
  await expect(details).toContainText('3 条记录');await expect(details.locator('tbody tr')).toHaveCount(3);
  await expect(details.locator('tbody')).toContainText('50');await page.keyboard.press('Escape');
  await chart.getByRole('button',{name:'图表选项',exact:true}).click();
  await chart.getByRole('button',{name:'明细',exact:true}).click();await ready(page);
  await chart.getByRole('button',{name:'关闭图表选项',exact:true}).click();
  await chart.locator('.recharts-bar-rectangle').first().click();await ready(page);
  await expect(table).toHaveText(before,{useInnerText:true});
  await expect(page.getByTestId('dataset-telemetry')).toContainText('6 / 6 行');
  await page.getByRole('button',{name:'保存与复用',exact:true}).click();
  const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'保存分析文件',exact:true}).click();
  const download=await downloadPromise,buffer=await readFile(await download.path()),saved=JSON.parse(buffer.toString());
  expect(saved.view.fullConfig.rows[0].field).toBe('Region');
  expect(saved.view.csc.analysisConfig.rows[0].field).toBe('Counterparty');
  expect(saved.view.csc.analysisConfig.filters[0].field).toBe('Counterparty');
  await page.keyboard.press('Escape');await chart.getByRole('button',{name:'使用透视表配置',exact:true}).click();await ready(page);
  await expect(chart.getByTestId('chart-analysis-state')).toHaveText('沿用透视表配置');
  await expect(table).toHaveText(before,{useInnerText:true});
  await page.reload();await page.getByRole('button',{name:'保存与复用',exact:true}).click();
  await page.getByLabel('选择分析文件',{exact:true}).setInputFiles({name:'saved.pivotstudio.json',mimeType:'application/json',buffer});await ready(page);
  await expect(table).toHaveText(before,{useInnerText:true});
  await expect(chart.getByTestId('chart-analysis-state')).toHaveText('图表独立配置');
  if(await chart.getByRole('button',{name:/调整图表字段/}).count())await chart.getByRole('button',{name:/调整图表字段/}).click();
  await expect(chart.getByLabel('行字段',{exact:true})).toHaveValue('Counterparty');
  expect((await new AxeBuilder({page}).include('#pivot-chart-container').analyze()).violations).toEqual([]);
  await page.screenshot({path:info.outputPath('independent-chart.png'),animations:'disabled'});
});
