// 1. 生成 XLSX 工作簿 (test_retail_sales.xlsx)
const ws = XLSX.utils.json_to_sheet(rawData);
// 设置列宽
ws['!cols'] = [
  { wch: 12 }, // 订单日期
  { wch: 10 }, // 销售大区
  { wch: 10 }, // 城市
  { wch: 14 }, // 销售渠道
  { wch: 12 }, // 商品类别
  { wch: 16 }, // 商品名称
  { wch: 14 }, // 客户类型
  { wch: 12 }, // 销售额
  { wch: 10 }, // 销量
  { wch: 12 }, // 成本
  { wch: 12 }, // 毛利润
  { wch: 10 }, // 是否促销
];
const wb = XLSX.utils.book_new();
XLSX.utils.book_append_sheet(wb, ws, '全渠道销售明细');
XLSX.writeFile(wb, 'test_retail_sales.xlsx');

// 2. 生成带 UTF-8 BOM 的 CSV（Excel双击直接完美展示中文）
const headers = Object.keys(rawData[0]);
const csvLines = [headers.join(',')];
rawData.forEach(row => {
  const line = headers.map(h => {
    const val = String(row[h]);
    return val.includes(',') ? `"${val}"` : val;
  }).join(',');
  csvLines.push(line);
});
const bom = '\uFEFF';
fs.writeFileSync('test_retail_sales.csv', bom + csvLines.join('\r\n'), 'utf8');

// 3. 复制到 public 目录
if (!fs.existsSync('public')) fs.mkdirSync('public');
fs.copyFileSync('test_retail_sales.xlsx', 'public/test_retail_sales.xlsx');
fs.copyFileSync('test_retail_sales.csv', 'public/test_retail_sales.csv');

