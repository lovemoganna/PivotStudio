export function setLocale(value) { locale = value === 'en' ? 'en' : 'zh'; document.documentElement.lang = locale === 'en' ? 'en' : 'zh-CN'; try { localStorage.setItem('pivotstudio_locale',locale); return true; } catch { return false; } }
export function t(value) { return locale === 'en' && typeof value === 'string' ? english[value] ?? value : value; }
